const translations: Record<string, TranslationTable> = { en, ru };

/** Normalizes CloudCLI/i18next locale values to a plugin translation locale. */
export function normalizeLocale(locale: string | null | undefined): string {
  return locale?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

/** Reads the host language for older CloudCLI versions that do not expose it in plugin context. */
export function detectHostLocale(contextLocale?: string): string {
  if (contextLocale) return normalizeLocale(contextLocale);
  try {
    return normalizeLocale(localStorage.getItem('userLanguage') || navigator.language);
  } catch {
    return 'en';
  }
}

/** Translates one plugin UI or Telegram message with lightweight named interpolation. */
export function translate(
  locale: string | null | undefined,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  const table = translations[normalizeLocale(locale)] || en;
  return table[key].replace(/\{\{(\w+)\}\}/g, (_match, name: string) => String(values[name] ?? ''));
}

export type { TranslationKey };
